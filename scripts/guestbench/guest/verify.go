// mib is one mebibyte, the unit of most verify.data sizes.
const mib = 1 << 20

// verifyRounds checks, in the first round only, that the tree returns the
// bytes git recorded for every tracked file and the bytes the guest writes
// through a range of write patterns. Both phases read after a cold reset,
// so the bytes come from the filesystem rather than the guest's caches.
func (r *runner) verifyRounds() (func(round int) error, error) {
	var blobs []blob
	listBlobs := func() (err error) {
		blobs, err = r.trackedBlobs()
		return err
	}
	dir := filepath.Join(r.scratch(), "verify")
	samples := verifySamples()
	write := func() error {
		if err := os.RemoveAll(dir); err != nil {
			return err
		}
		if err := os.MkdirAll(dir, 0o755); err != nil {
			return err
		}
		for _, s := range samples {
			if err := s.write(dir, s.want()); err != nil {
				return fmt.Errorf("write %s: %w", s.names[0], err)
			}
		}
		return nil
	}
	checkTree := func() (result, error) { return r.checkBlobs(blobs) }
	checkData := func() (result, error) { return checkSamples(dir, samples) }
	return func(round int) error {
		if round > 0 {
			return nil
		}
		if err := r.phases(round, []phase{
			{name: "verify.tree", before: listBlobs, cold: true, body: checkTree},
			{name: "verify.data", before: write, cold: true, body: checkData},
		}); err != nil {
			return err
		}
		return os.RemoveAll(dir)
	}, nil
}

// blob is one tracked regular file and the object id git recorded for it.
type blob struct {
	path string // relative to the tree
	id   string // hex SHA-1 of the blob
}

// trackedBlobs lists the index's regular files with their blob ids; symlinks
// and gitlinks have no file content to compare.
func (r *runner) trackedBlobs() ([]blob, error) {
	// Only stdout lists the index; warnings go to stderr.
	var out bytes.Buffer
	cmd := r.gitCmd("ls-files", "-s", "-z")
	cmd.Stdout = &out
	if _, err := runCmd(cmd); err != nil {
		return nil, err
	}
	var blobs []blob
	for rec := range bytes.SplitSeq(out.Bytes(), []byte{0}) {
		if len(rec) == 0 {
			continue
		}
		meta, path, ok := strings.Cut(string(rec), "\t")
		fields := strings.Fields(meta)
		if !ok || len(fields) != 3 {
			return nil, fmt.Errorf("git ls-files: malformed entry %q", rec)
		}
		if fields[0] == "120000" || fields[0] == "160000" {
			continue
		}
		if len(fields[1]) != 2*sha1.Size {
			return nil, fmt.Errorf("%s: object id %s is not SHA-1", path, fields[1])
		}
		blobs = append(blobs, blob{path: path, id: fields[1]})
	}
	return blobs, nil
}

// checkBlobs hashes every blob's file through the tree on Plan.Jobs workers
// and compares it with the id git recorded.
func (r *runner) checkBlobs(blobs []blob) (result, error) {
	var hashed atomic.Int64
	err := parallel(r.plan.Jobs, len(blobs), func(i int) error {
		n, err := checkBlob(filepath.Join(r.root, blobs[i].path), blobs[i].id)
		hashed.Add(n)
		if err != nil {
			return fmt.Errorf("%s: %w", blobs[i].path, err)
		}
		return nil
	})
	return result{ops: int64(len(blobs)), bytes: hashed.Load()}, err
}

// checkBlob computes the git blob id of the file at path, SHA-1 over
// "blob <size>\0" and the content, compares it with want and returns the
// content bytes it hashed.
func checkBlob(path, want string) (int64, error) {
	f, err := os.Open(path)
	if err != nil {
		return 0, err
	}
	defer f.Close()
	info, err := f.Stat()
	if err != nil {
		return 0, err
	}
	if !info.Mode().IsRegular() {
		return 0, fmt.Errorf("mode %s, want a regular file", info.Mode())
	}
	h := sha1.New()
	fmt.Fprintf(h, "blob %d\x00", info.Size())
	n, err := io.Copy(h, f)
	if err != nil {
		return n, err
	}
	if n != info.Size() {
		return n, fmt.Errorf("read %d bytes, stat reports %d", n, info.Size())
	}
	if got := hex.EncodeToString(h.Sum(nil)); got != want {
		return n, fmt.Errorf("content hashes to blob %s, git recorded %s", got, want)
	}
	return n, nil
}

// sample is one file verify.data writes and reads back. want regenerates its
// expected content, and write produces that content in dir by the sample's
// write pattern, so the two cannot drift apart.
type sample struct {
	names []string // names that must read as want; the first is written
	gone  []string // names that must no longer exist
	want  func() []byte
	write func(dir string, want []byte) error
}

// genStream is the second PCG seed of every generated byte stream.
const genStream = 0x9e3779b97f4a7c15

// gen returns n bytes of the deterministic stream seed names; a shorter
// request returns a prefix of a longer one.
func gen(seed uint64, n int) []byte {
	r := rand.New(rand.NewPCG(seed, genStream))
	b := make([]byte, n)
	var w [8]byte
	for i := 0; i < n; i += len(w) {
		binary.LittleEndian.PutUint64(w[:], r.Uint64())
		copy(b[i:], w[:])
	}
	return b
}

// alt is the seed of a sample's second stream, for the bytes that replace
// or follow its first.
func alt(seed uint64) uint64 { return seed + 1<<32 }

// patch copies p into base at off and returns base.
func patch(base []byte, off int, p []byte) []byte {
	copy(base[off:], p)
	return base
}

// verifySamples lists the files verify.data writes, each with its own seed.
func verifySamples() []sample {
	return []sample{
		wholeSample("empty", 1, 0),
		wholeSample("one", 2, 1),
		wholeSample("page-1", 3, 4095),
		wholeSample("page", 4, 4096),
		wholeSample("page+1", 5, 4097),
		wholeSample("mib-1", 6, mib-1),
		wholeSample("mib", 7, mib),
		wholeSample("mib+1", 8, mib+1),
		chunkedSample("chunked", 9),
		backwardSample("backward", 10),
		overwriteSample("overwrite", 11),
		extendSample("extend", 12),
		shrinkSample("shrink-append", 13),
		mmapSample("mmap", 14),
		renameSample("renamed", 15),
		linkSample("linked", 16),
	}
}

// wholeSample is size generated bytes written in one call.
func wholeSample(name string, seed uint64, size int) sample {
	return sample{
		names: []string{name},
		want:  func() []byte { return gen(seed, size) },
		write: func(dir string, want []byte) error {
			return os.WriteFile(filepath.Join(dir, name), want, 0o644)
		},
	}
}

// chunkedSample is 5 MiB written in 64 KiB writes.
func chunkedSample(name string, seed uint64) sample {
	const chunk = 64 << 10
	return sample{
		names: []string{name},
		want:  func() []byte { return gen(seed, 5*mib) },
		write: func(dir string, want []byte) error {
			return writeWith(filepath.Join(dir, name), os.O_CREATE|os.O_TRUNC, func(f *os.File) error {
				for off := 0; off < len(want); off += chunk {
					if _, err := f.Write(want[off:min(off+chunk, len(want))]); err != nil {
						return err
					}
				}
				return nil
			})
		},
	}
}

// backwardSample is 3 MiB written back to front in 4 KiB pwrites.
func backwardSample(name string, seed uint64) sample {
	const block = 4 << 10
	return sample{
		names: []string{name},
		want:  func() []byte { return gen(seed, 3*mib) },
		write: func(dir string, want []byte) error {
			return writeWith(filepath.Join(dir, name), os.O_CREATE|os.O_TRUNC, func(f *os.File) error {
				for end := len(want); end > 0; {
					start := max(0, end-block)
					if _, err := f.WriteAt(want[start:end], int64(start)); err != nil {
						return err
					}
					end = start
				}
				return nil
			})
		},
	}
}

// overwriteSample is 2 MiB whose bytes [777, 1 MiB + 333) are rewritten
// after a close and reopen.
func overwriteSample(name string, seed uint64) sample {
	const start, end = 777, mib + 333
	return sample{
		names: []string{name},
		want:  func() []byte { return patch(gen(seed, 2*mib), start, gen(alt(seed), end-start)) },
		write: func(dir string, want []byte) error {
			path := filepath.Join(dir, name)
			if err := os.WriteFile(path, gen(seed, 2*mib), 0o644); err != nil {
				return err
			}
			return writeWith(path, 0, func(f *os.File) error {
				_, err := f.WriteAt(want[start:end], start)
				return err
			})
		},
	}
}

// extendSample is 10 bytes extended by truncate to 1 MiB + 5, the rest a
// hole that must read as zeros.
func extendSample(name string, seed uint64) sample {
	const head, size = 10, mib + 5
	return sample{
		names: []string{name},
		want:  func() []byte { return append(gen(seed, head), make([]byte, size-head)...) },
		write: func(dir string, want []byte) error {
			path := filepath.Join(dir, name)
			if err := os.WriteFile(path, want[:head], 0o644); err != nil {
				return err
			}
			return os.Truncate(path, int64(len(want)))
		},
	}
}

// shrinkSample is 2 MiB truncated to 4097 bytes, then appended 100 bytes.
func shrinkSample(name string, seed uint64) sample {
	const kept, tail = 4097, 100
	return sample{
		names: []string{name},
		want:  func() []byte { return append(gen(seed, kept), gen(alt(seed), tail)...) },
		write: func(dir string, want []byte) error {
			path := filepath.Join(dir, name)
			if err := os.WriteFile(path, gen(seed, 2*mib), 0o644); err != nil {
				return err
			}
			if err := os.Truncate(path, kept); err != nil {
				return err
			}
			return writeWith(path, os.O_APPEND, func(f *os.File) error {
				_, err := f.Write(want[kept:])
				return err
			})
		},
	}
}

// mmapSample is 1 MiB written through a shared writable mapping and
// msync'ed.
func mmapSample(name string, seed uint64) sample {
	return sample{
		names: []string{name},
		want:  func() []byte { return gen(seed, mib) },
		write: func(dir string, want []byte) error {
			return writeWith(filepath.Join(dir, name), os.O_CREATE|os.O_TRUNC, func(f *os.File) error {
				if err := f.Truncate(int64(len(want))); err != nil {
					return err
				}
				m, err := unix.Mmap(int(f.Fd()), 0, len(want), unix.PROT_READ|unix.PROT_WRITE, unix.MAP_SHARED)
				if err != nil {
					return err
				}
				copy(m, want)
				return errors.Join(unix.Msync(m, unix.MS_SYNC), unix.Munmap(m))
			})
		},
	}
}

// renameSample is 100 KiB written under a temporary name, then renamed.
func renameSample(name string, seed uint64) sample {
	tmp := name + ".tmp"
	return sample{
		names: []string{name},
		gone:  []string{tmp},
		want:  func() []byte { return gen(seed, 100<<10) },
		write: func(dir string, want []byte) error {
			if err := os.WriteFile(filepath.Join(dir, tmp), want, 0o644); err != nil {
				return err
			}
			return os.Rename(filepath.Join(dir, tmp), filepath.Join(dir, name))
		},
	}
}

// linkSample is 256 KiB hard-linked under a second name, whose first 4 KiB
// are then rewritten through that name, so both names must show the write.
func linkSample(name string, seed uint64) sample {
	const size, head = 256 << 10, 4 << 10
	link := name + ".link"
	return sample{
		names: []string{name, link},
		want:  func() []byte { return patch(gen(seed, size), 0, gen(alt(seed), head)) },
		write: func(dir string, want []byte) error {
			path := filepath.Join(dir, name)
			if err := os.WriteFile(path, gen(seed, size), 0o644); err != nil {
				return err
			}
			if err := os.Link(path, filepath.Join(dir, link)); err != nil {
				return err
			}
			return writeWith(filepath.Join(dir, link), 0, func(f *os.File) error {
				_, err := f.WriteAt(want[:head], 0)
				return err
			})
		},
	}
}

// writeWith opens path read-write with flag added, runs fn on it and closes
// it, reporting the first error.
func writeWith(path string, flag int, fn func(f *os.File) error) error {
	f, err := os.OpenFile(path, os.O_RDWR|flag, 0o644)
	if err != nil {
		return err
	}
	if err := fn(f); err != nil {
		f.Close()
		return err
	}
	return f.Close()
}

// checkSamples reads every sample's names in dir back and compares them
// with the regenerated content; renamed-away names must be gone.
func checkSamples(dir string, samples []sample) (result, error) {
	var res result
	for _, s := range samples {
		want := s.want()
		for _, name := range s.names {
			got, err := os.ReadFile(filepath.Join(dir, name))
			if err != nil {
				return res, err
			}
			if err := compareBytes(got, want); err != nil {
				return res, fmt.Errorf("%s: %w", name, err)
			}
			res.ops++
			res.bytes += int64(len(want))
		}
		for _, name := range s.gone {
			if _, err := os.Lstat(filepath.Join(dir, name)); !errors.Is(err, fs.ErrNotExist) {
				return res, fmt.Errorf("%s: still present after its rename (lstat: %v)", name, err)
			}
		}
	}
	return res, nil
}

// compareBytes reports the first offset where got differs from want, or a
// length mismatch.
func compareBytes(got, want []byte) error {
	if bytes.Equal(got, want) {
		return nil
	}
	for i := range min(len(got), len(want)) {
		if got[i] != want[i] {
			return fmt.Errorf("byte %d is %#02x, want %#02x (size %d, want %d)", i, got[i], want[i], len(got), len(want))
		}
	}
	return fmt.Errorf("size %d, want %d (equal up to the shorter)", len(got), len(want))
}
